def test_read_json_with_nodes_materialises_only_those_nodes():
    """Unrequested nodes keep their wiring but drop their values."""
    comp = Computation()
    comp.add_node("a", value=1)
    comp.add_node("b", value=pd.DataFrame({"x": [1, 2]}))
    comp.add_node("c", value="kept")
    buf = io.StringIO()
    comp.write_json(buf)
    buf.seek(0)

    got = Computation.read_json(buf, nodes=["a", "c"])
    assert got.v.a == 1
    assert got.v.c == "kept"
    assert got.state("b") == States.UNINITIALIZED
    # The node itself is still there — only its payload was skipped.
    assert "b" in {str(k) for k in got.dag.nodes}


def test_partial_read_keeps_graph_shape():
    """Edges survive a partial read, so the graph is still recomputable."""
    comp = Computation()
    comp.add_node("a", value=3)
    comp.add_node("b", lambda a: a + 1)
    comp.compute_all()
    s = ComputationSerializer(use_dill_for_functions=True)
    buf = io.StringIO()
    comp.write_json(buf, serializer=s)
    buf.seek(0)

    got = Computation.read_json(buf, serializer=s, nodes=["a"])
    assert got.v.a == 3
    # 'b' was skipped, but it has a function and its input is loaded, so it is
    # computable rather than uninitialized — the graph can just be recomputed.
    assert got.state("b") == States.COMPUTABLE
    got.compute_all()
    assert got.v.b == 4


def test_partial_read_settles_a_chain_of_skipped_nodes():
    """Skipped nodes resolve in topological order, not just one level deep."""
    comp = Computation()
    comp.add_node("a", value=3)
    comp.add_node("b", fx_add_one, kwds={"x": "a"})
    comp.add_node("c", fx_double, kwds={"x": "b"})
    comp.compute_all()
    buf = io.StringIO()
    comp.write_json(buf)
    buf.seek(0)

    got = Computation.read_json(buf, nodes=["a"])
    assert got.state("b") == States.COMPUTABLE
    # 'c' cannot be computable yet — its own input is not loaded.
    assert got.state("c") == States.UNINITIALIZED
    got.compute_all()
    assert got.v.c == 8
