def test_future_version_is_rejected_with_an_actionable_message():
    """A document from a newer loman fails loudly rather than half-parsing."""
    doc = {"version": FORMAT_VERSION + 1, "nodes": [], "edges": []}
    with pytest.raises(SerializationError) as exc:
        Computation.read_json(io.StringIO(json.dumps(doc)))
    msg = str(exc.value)
    assert str(FORMAT_VERSION + 1) in msg
    assert "Upgrade loman" in msg


def test_missing_version_is_rejected():
    """A document with no version field cannot be identified, so it is refused."""
    doc = {"nodes": [], "edges": []}
    with pytest.raises(SerializationError, match="no 'version' field"):
        Computation.read_json(io.StringIO(json.dumps(doc)))


def test_non_integer_version_is_rejected():
    """A version that is not an integer is a malformed document."""
    doc = {"version": "2", "nodes": [], "edges": []}
    with pytest.raises(SerializationError, match="non-integer format version"):
        Computation.read_json(io.StringIO(json.dumps(doc)))


def test_boolean_version_is_rejected():
    """``True`` is an int in Python; it is still not a version number."""
    doc = {"version": True, "nodes": [], "edges": []}
    with pytest.raises(SerializationError, match="non-integer format version"):
        Computation.read_json(io.StringIO(json.dumps(doc)))


def test_too_old_version_is_rejected(monkeypatch):
    """A version below the supported floor is refused, not guessed at."""
    monkeypatch.setattr("loman.serialization.computation.MIN_SUPPORTED_VERSION", 2)
    doc = {"version": 1, "nodes": [], "edges": []}
    with pytest.raises(SerializationError, match="no longer reads"):
        Computation.read_json(io.StringIO(json.dumps(doc)))


def test_current_version_is_written():
    """Fresh documents carry the current format version."""
    comp = Computation()
    comp.add_node("a", value=1)
    data = json.loads(ComputationSerializer().dumps(comp))
    assert data["version"] == FORMAT_VERSION


